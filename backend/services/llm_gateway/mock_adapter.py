from typing import Any, Dict, List

from models.llm_payload_models import LLMPayloadResponse
from services.llm_gateway.base import LLMAdapter

_NOT_FOUND = (
    "[Mock] No relevant content found in this document for your query. "
    "Try different search terms or lower top_k."
)


class MockLLMAdapter(LLMAdapter):
    @property
    def is_configured(self) -> bool:
        return True

    def ask(self, query: str, payload: LLMPayloadResponse) -> str:
        chunks: List[Dict[str, Any]] = (
            payload.universal_payload.get("document_context", {}).get("chunks", [])
        )
        if not chunks:
            return _NOT_FOUND

        if any("citation_id" in chunk for chunk in chunks):
            return self._grounded_answer(chunks)

        lines = [
            f"[Mock] Based on the document, here are the {len(chunks)} most relevant "
            f"section(s) for your query:",
            "",
        ]
        for i, chunk in enumerate(chunks, 1):
            section = " > ".join(chunk["section_path"]) if chunk["section_path"] else "(root)"
            text: str = chunk["text"]
            preview = text[:200] + ("…" if len(text) > 200 else "")
            short_id = chunk["chunk_id"][:8]
            lines.append(f"{i}. [{section}] (chunk_id: {short_id}…)")
            lines.append(f"   {preview}")
            lines.append("")

        lines.append(
            "[Mock] This answer was generated by the mock provider. "
            "No real LLM was called."
        )
        return "\n".join(lines)

    @staticmethod
    def _grounded_answer(chunks: List[Dict[str, Any]]) -> str:
        lines = [
            "[Mock] Grounded answer from the provided document context:",
            "",
        ]
        for chunk in chunks[:3]:
            citation_id = chunk.get("citation_id", "C?")
            section_path = chunk.get("section_path") or []
            section = " > ".join(section_path) if section_path else "(root)"
            text = str(chunk.get("text", ""))
            preview = text[:180] + ("…" if len(text) > 180 else "")
            lines.append(f"- [{citation_id}] {section}: {preview}")
        lines += [
            "",
            "[Mock] This grounded answer used only the supplied citation context. "
            "No real LLM was called.",
        ]
        return "\n".join(lines)
